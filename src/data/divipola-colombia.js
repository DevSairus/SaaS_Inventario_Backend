/** Mapa rápido code → registro, para lookups O(1) sin recorrer el arreglo. */
const DIVIPOLA_CITIES_BY_CODE = DIVIPOLA_CITIES.reduce((acc, c) => {
  acc[c.code] = c;
  return acc;
}, {});

const DIVIPOLA_DEPARTMENTS_BY_CODE = DIVIPOLA_DEPARTMENTS.reduce((acc, d) => {
  acc[d.code] = d;
  return acc;
}, {});

/**
 * Valida que un city_code exista en DIVIPOLA y retorna el registro completo
 * (incluyendo el departamento). Retorna null si el código no existe.
 */
function resolveCity(cityCode) {
  const city = DIVIPOLA_CITIES_BY_CODE[cityCode];
  if (!city) return null;
  const department = DIVIPOLA_DEPARTMENTS_BY_CODE[city.department_code];
  return {
    cityCode: city.code,
    cityName: city.name,
    departmentCode: city.department_code,
    departmentName: department ? department.name : null,
  };
}

